results = []

for name, seq in sequences.items():
    analysed = ProteinAnalysis(seq)

    length = len(seq)
    mw = analysed.molecular_weight()
    pI = analysed.isoelectric_point()
    gravy = analysed.gravy()  # hydrophobicity

    # Net charge approximation
    charge = seq.count("K") + seq.count("R") - seq.count("D") - seq.count("E")

    results.append([name, length, round(mw,2), round(pI,2), round(gravy,2), charge])

df = pd.DataFrame(results, columns=["Sequence", "Length", "Molecular Weight", "pI", "Hydrophobicity (GRAVY)", "Net Charge"])
